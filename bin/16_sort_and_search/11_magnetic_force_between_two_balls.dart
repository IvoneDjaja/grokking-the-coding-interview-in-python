    position.sort();
    final minHeap = HeapPriorityQueue<int>();

    for (var i = 0; i < position.length - 1; i++) {
      final pos1 = position[i];
      final pos2 = position[i + 1];
      minHeap.add(pos2 - pos1);
    }

